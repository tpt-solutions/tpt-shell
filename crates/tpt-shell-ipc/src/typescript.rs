//! TypeScript client generator (spec M2, codegen). Produces one `.ts` file with an argument
//! type per command and a typed wrapper that calls `window.tpt.invoke`.
//!
//! A `job` command's wrapper resolves to a [`JobHandle`]: its id, and `cancel()`, which calls
//! the `job.cancel` command. The module also types the job events (`job.progress`,
//! `job.result`, `job.failed`, `job.cancelled`) in `JobEvents`, so `tpt.on` callbacks can be
//! typed. [`generate_mock`] writes a basic mock backend for the same contract.
//!
//! Output is deterministic: commands are sorted by name (see [`Contract::commands`]) and
//! struct fields keep their declared order.
//!
//! Gap: contracts do not describe results yet, so wrappers return `Promise<unknown>`.

use crate::contract::{Command, Contract, Kind};
use crate::schema::{Field, Schema};

/// Generates the client module for `contract`.
pub fn generate(contract: &Contract) -> String {
    let mut out = String::new();
    out.push_str("// Generated by tpt-shell from the command contract. Do not edit.\n");
    out.push_str("// Calls go through window.tpt.invoke (js/runtime/tpt-shell.js).\n\n");

    if contract.commands().any(|c| c.kind == Kind::Job) {
        out.push_str(JOB_TYPES);
    }

    for command in contract.commands() {
        out.push_str(&args_declaration(command));
        out.push('\n');
    }

    out.push_str("export const commands = {\n");
    for command in contract.commands() {
        out.push_str(&wrapper(command));
    }
    out.push_str("} as const;\n");
    out
}

/// Generates a mock backend for `contract`: a `mockResponses` table with one entry per command
/// and `installMock`, which replaces `window.tpt.invoke` with a version that answers from the
/// table. A command with no response answers `null`; an unknown command is refused with
/// `IPC_UNKNOWN_COMMAND`, as the router does.
pub fn generate_mock(contract: &Contract) -> String {
    let mut out = String::new();
    out.push_str("// Generated by tpt-shell from the command contract. Do not edit.\n");
    out.push_str("// Basic mock: no argument checks, no capability checks.\n\n");
    out.push_str("export const mockCommands: readonly string[] = [\n");
    for command in contract.commands() {
        out.push_str(&format!("  {},\n", string_literal(command.name)));
    }
    out.push_str("];\n\n");
    out.push_str("/** Responses by command name. Missing commands answer `null`. */\n");
    out.push_str("export const mockResponses: Record<string, unknown> = {};\n\n");
    out.push_str(MOCK_INSTALL);
    out
}

/// PascalCase name for a command's argument type: `list_dir` becomes `ListDirArgs`.
fn type_name(command: &str) -> String {
    let mut name = String::new();
    for part in command.split(['_', '-', '.']).filter(|p| !p.is_empty()) {
        let mut chars = part.chars();
        if let Some(first) = chars.next() {
            name.extend(first.to_uppercase());
            name.push_str(chars.as_str());
        }
    }
    name.push_str("Args");
    name
}

fn args_declaration(command: &Command) -> String {
    let name = type_name(command.name);
    match &command.args {
        Schema::Struct(fields) => {
            let mut out = format!("export interface {name} {}\n", struct_body(fields, 0));
            out.insert_str(0, &jsdoc(command, ""));
            out
        }
        other => format!(
            "{}export type {name} = {};\n",
            jsdoc(command, ""),
            ts_type(other, 0)
        ),
    }
}

fn wrapper(command: &Command) -> String {
    let name = type_name(command.name);
    let mut out = jsdoc(command, "  ");
    let call = string_literal(command.name);
    match command.kind {
        Kind::Job => out.push_str(&format!(
            "  {}(args: {name}): Promise<JobHandle> {{\n    return window.tpt.invoke({call}, args).then((r: {{ job: number }}) => ({{\n      id: r.job,\n      cancel: () => window.tpt.invoke(\"job.cancel\", {{ job: r.job }}),\n    }}));\n  }},\n",
            method_key(command.name),
        )),
        Kind::Sync | Kind::Async => out.push_str(&format!(
            "  {}(args: {name}): Promise<unknown> {{\n    return window.tpt.invoke({call}, args);\n  }},\n",
            method_key(command.name),
        )),
    }
    out
}

/// Object keys that are not plain identifiers are quoted.
fn method_key(name: &str) -> String {
    let plain = name
        .chars()
        .next()
        .is_some_and(|c| c.is_ascii_alphabetic() || c == '_')
        && name.chars().all(|c| c.is_ascii_alphanumeric() || c == '_');
    if plain {
        name.to_string()
    } else {
        string_literal(name)
    }
}

fn jsdoc(command: &Command, indent: &str) -> String {
    let kind = command.kind.as_str();
    let mut out = format!("{indent}/**\n");
    out.push_str(&format!(
        "{indent} * Command `{}` ({kind}).\n",
        command.name
    ));
    if let Some(capability) = command.capability {
        out.push_str(&format!("{indent} * Requires capability `{capability}`.\n"));
    }
    if command.kind == Kind::Job {
        out.push_str(&format!(
            "{indent} * Resolves to a job handle. Progress and results arrive as `job.*` events.\n"
        ));
    }
    out.push_str(&format!("{indent} */\n"));
    out
}

/// TypeScript type for one schema, indented for nesting at `depth`.
fn ts_type(schema: &Schema, depth: usize) -> String {
    match schema {
        Schema::Bool => "boolean".into(),
        Schema::Int { .. } | Schema::Float { .. } => "number".into(),
        Schema::Str { .. } => "string".into(),
        Schema::Enum(options) => options
            .iter()
            .map(|o| string_literal(o))
            .collect::<Vec<_>>()
            .join(" | "),
        Schema::Optional(inner) => format!("{} | null", ts_type(inner, depth)),
        Schema::List { item, .. } => {
            let inner = ts_type(item, depth);
            if needs_parens(item) {
                format!("({inner})[]")
            } else {
                format!("{inner}[]")
            }
        }
        Schema::Map { value, .. } => format!("{{ [key: string]: {} }}", ts_type(value, depth)),
        Schema::Struct(fields) => struct_body(fields, depth),
    }
}

/// Unions need parentheses inside an array type.
fn needs_parens(schema: &Schema) -> bool {
    matches!(schema, Schema::Enum(_) | Schema::Optional(_))
}

fn struct_body(fields: &[Field], depth: usize) -> String {
    if fields.is_empty() {
        return "{}".into();
    }
    let pad = "  ".repeat(depth + 1);
    let mut out = String::from("{\n");
    for field in fields {
        let (optional, schema) = match &field.schema {
            Schema::Optional(inner) => ("?", *inner),
            other => ("", other),
        };
        let ty = match &field.schema {
            // An optional field may be absent or null.
            Schema::Optional(_) => format!("{} | null", ts_type(schema, depth + 1)),
            _ => ts_type(schema, depth + 1),
        };
        out.push_str(&format!("{pad}{}{optional}: {ty};\n", field.name));
    }
    out.push_str(&format!("{}}}", "  ".repeat(depth)));
    out
}

fn string_literal(text: &str) -> String {
    serde_json::to_string(text).unwrap_or_else(|_| "\"\"".into())
}

/// Types for job handles and job events, emitted once when the contract has a job command.
const JOB_TYPES: &str = "/** A started job: its id, and a way to cancel it. */
export interface JobHandle {
  readonly id: number;
  cancel(): Promise<unknown>;
}

/** Payloads of the job events, by event name, for typed `tpt.on` callbacks. */
export interface JobEvents {
  \"job.progress\": { job: number; done: number; total: number };
  \"job.result\": { job: number; data: unknown };
  \"job.failed\": { job: number; code: string; message: string };
  \"job.cancelled\": { job: number };
}

";

/// The mock install function, emitted by [`generate_mock`].
const MOCK_INSTALL: &str = "/** Replaces window.tpt.invoke with the mock. Returns a function that restores the original. */
export function installMock(responses: Record<string, unknown> = mockResponses): () => void {
  const tpt = (window as any).tpt;
  const original = tpt.invoke;
  tpt.invoke = (cmd: string, _args?: unknown): Promise<unknown> => {
    if (!mockCommands.includes(cmd)) {
      return Promise.reject({ ok: false, error: { code: \"IPC_UNKNOWN_COMMAND\", message: `no command named \\`${cmd}\\`` } });
    }
    return Promise.resolve(cmd in responses ? responses[cmd] : null);
  };
  return () => {
    tpt.invoke = original;
  };
}
";

#[cfg(test)]
mod tests {
    use super::*;
    use crate::contract::{Command, Contract, Kind};
    use crate::schema::{Field, Schema};

    const PAYLOAD: &[Field] = &[
        Field {
            name: "name",
            schema: Schema::Str {
                max_len: 8,
                chars: None,
            },
        },
        Field {
            name: "level",
            schema: Schema::Optional(&Schema::Int { min: 0, max: 9 }),
        },
    ];

    fn contract() -> Contract {
        let mut c = Contract::new();
        c.add(Command {
            name: "zeta_op",
            kind: Kind::Sync,
            capability: None,
            args: Schema::Struct(&[]),
        })
        .unwrap();
        c.add(Command {
            name: "set_mode",
            kind: Kind::Sync,
            capability: Some("device.serial"),
            args: Schema::Struct(&[
                Field {
                    name: "mode",
                    schema: Schema::Enum(&["read", "write"]),
                },
                Field {
                    name: "tags",
                    schema: Schema::List {
                        item: &Schema::Str {
                            max_len: 4,
                            chars: None,
                        },
                        max_len: 3,
                    },
                },
                Field {
                    name: "payload",
                    schema: Schema::Struct(PAYLOAD),
                },
            ]),
        })
        .unwrap();
        c
    }

    #[test]
    fn names_become_pascal_case_argument_types() {
        assert_eq!(type_name("list_dir"), "ListDirArgs");
        assert_eq!(type_name("open-file.v2"), "OpenFileV2Args");
    }

    #[test]
    fn golden_client() {
        let expected = r#"// Generated by tpt-shell from the command contract. Do not edit.
// Calls go through window.tpt.invoke (js/runtime/tpt-shell.js).

/**
 * Command `set_mode` (sync).
 * Requires capability `device.serial`.
 */
export interface SetModeArgs {
  mode: "read" | "write";
  tags: string[];
  payload: {
    name: string;
    level?: number | null;
  };
}

/**
 * Command `zeta_op` (sync).
 */
export interface ZetaOpArgs {}

export const commands = {
  /**
   * Command `set_mode` (sync).
   * Requires capability `device.serial`.
   */
  set_mode(args: SetModeArgs): Promise<unknown> {
    return window.tpt.invoke("set_mode", args);
  },
  /**
   * Command `zeta_op` (sync).
   */
  zeta_op(args: ZetaOpArgs): Promise<unknown> {
    return window.tpt.invoke("zeta_op", args);
  },
} as const;
"#;
        assert_eq!(generate(&contract()), expected);
    }

    #[test]
    fn generation_is_deterministic() {
        assert_eq!(generate(&contract()), generate(&contract()));
    }

    #[test]
    fn unusual_command_names_are_quoted_as_keys() {
        let mut c = Contract::new();
        c.add(Command {
            name: "open-file",
            kind: Kind::Sync,
            capability: None,
            args: Schema::Bool,
        })
        .unwrap();
        let out = generate(&c);
        assert!(out.contains("\"open-file\"(args: OpenFileArgs)"), "{out}");
        assert!(out.contains("export type OpenFileArgs = boolean;"));
    }

    #[test]
    fn job_commands_resolve_to_a_handle_with_cancel() {
        let mut c = Contract::new();
        c.add(Command {
            name: "scan",
            kind: Kind::Job,
            capability: Some("fs.read"),
            args: Schema::Struct(&[]),
        })
        .unwrap();
        let out = generate(&c);
        assert!(out.contains("export interface JobHandle {"), "{out}");
        assert!(out.contains("\"job.progress\": { job: number; done: number; total: number };"));
        assert!(
            out.contains("scan(args: ScanArgs): Promise<JobHandle> {"),
            "{out}"
        );
        assert!(
            out.contains("window.tpt.invoke(\"job.cancel\", { job: r.job })"),
            "{out}"
        );
    }

    #[test]
    fn job_types_are_left_out_without_jobs() {
        assert!(!generate(&contract()).contains("JobHandle"));
    }

    #[test]
    fn mock_lists_every_command_and_refuses_unknown_ones() {
        let out = generate_mock(&contract());
        assert!(out.contains("  \"set_mode\",\n  \"zeta_op\",\n"), "{out}");
        assert!(out.contains("IPC_UNKNOWN_COMMAND"));
        assert_eq!(generate_mock(&contract()), generate_mock(&contract()));
    }
}
